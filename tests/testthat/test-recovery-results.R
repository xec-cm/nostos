test_that("sample and episode views project the accepted values in fixed atomic columns", {
  tse <- add_recovery(recovery_parent(), "antibiotic", observed_rule())
  samples <- results_preserving_input(tse[, rev(colnames(tse))], "sample")
  common <- c("analysis_id", "view_scope", "current_present", "result_state",
              "structural_valid", "validation_complete", "dependencies")
  expect_named(samples, c(common, "sample_id", "subject_id", "episode_id", "time",
                          "relative_time", "included", "is_reference", "deviation",
                          "deviation_status"))
  expect_identical(samples$sample_id, c("b1", paste0("s", 1:6)))
  expect_identical(samples$subject_id, rep("participant_1", 7))
  expect_identical(samples$episode_id, rep("episode_1", 7))
  expect_identical(samples$time, c(8, 10, 12, 14, 16, 18, 20))
  expect_identical(samples$relative_time, c(-2, 0, 2, 4, 6, 8, 10))
  expect_identical(samples$is_reference, c(TRUE, rep(FALSE, 6)))
  expect_identical(samples$included, rep(TRUE, 7))
  expect_identical(samples$deviation, c(0, 0.75, 0.25, 0.125, 0.125, 0.5, 0.125))
  expect_identical(samples$deviation_status, rep("computed", 7))
  expect_identical(samples$result_state, rep("available", 7))
  expect_identical(samples$dependencies, rep("unchanged", 7))
  expect_true(all(samples$structural_valid & samples$validation_complete & samples$current_present))

  episodes <- results_preserving_input(tse)
  expect_named(episodes, c(common, "episode_id", "subject_id", "reference_support",
                           "n_baseline_samples", "n_baseline_times", "baseline_diameter",
                           "status", "reason", "coverage", "first_perturbation_time",
                           "first_return_time", "candidate_time", "confirmation_time",
                           "rebound_time", "last_observed_time", "n_window_visits"))
  expect_identical(episodes$reference_support, "single_sample")
  expect_identical(episodes$n_baseline_samples, 1L)
  expect_identical(episodes$n_baseline_times, 1L)
  expect_identical(episodes$baseline_diameter, NA_real_)
  expect_identical(episodes$status, "confirmed_return")
  expect_identical(episodes$reason, NA_character_)
  expect_identical(episodes$coverage, "reaches_horizon")
  expect_identical(episodes$first_perturbation_time, 0)
  expect_identical(episodes$first_return_time, 2)
  expect_identical(episodes$candidate_time, 2)
  expect_identical(episodes$confirmation_time, 6)
  expect_identical(episodes$rebound_time, 8)
  expect_identical(episodes$last_observed_time, 10)
  expect_identical(episodes$n_window_visits, 6L)
  expect_identical(episodes$result_state, "available")
  expect_true(all(vapply(as.list(samples), is.atomic, logical(1))))
  expect_true(all(vapply(as.list(episodes), is.atomic, logical(1))))
  expect_identical(as.data.frame(samples)$sample_id, samples$sample_id)
  expect_identical(as.data.frame(episodes)$validation_complete, TRUE)
})

test_that("absent stages, empty baselines and exclusions have distinct availability", {
  registered <- register_fixture(registration_fixture(trees = TRUE))
  before <- results_preserving_input(registered)
  expect_identical(before$result_state, rep("not_computed", 2))
  expect_identical(before$n_window_visits, rep(NA_integer_, 2))
  expect_identical(before$n_baseline_samples, rep(NA_integer_, 2))
  sample_before <- results_preserving_input(registered, "sample")
  expect_identical(sample_before$is_reference, rep(NA, 6))
  expect_identical(sample_before$result_state, rep("not_computed", 6))

  reference <- add_reference(registered, "antibiotic", "s1", assay = "counts")
  support <- results_preserving_input(reference)
  expect_identical(support$reference_support, c("single_sample", "missing_baseline"))
  expect_identical(support$n_baseline_samples, c(1L, 0L))
  expect_identical(support$n_baseline_times, c(1L, 0L))
  expect_identical(support$status, rep(NA_character_, 2))
  expect_identical(support$result_state, rep("not_computed", 2))
  deviation <- add_deviation(reference, "antibiotic")
  samples <- results_preserving_input(deviation, "sample")
  expect_identical(
    samples$deviation_status,
    c(rep("computed", 3), rep("missing_baseline", 2), "excluded")
  )
  expect_identical(samples$result_state, rep("available", 6))
  expect_identical(samples$subject_id, c(rep("p1", 5), NA_character_))
  expect_identical(samples$relative_time, c(-7, 0, 7, -8, 1, NA_real_))
  expect_identical(samples$is_reference, c(TRUE, rep(FALSE, 5)))
  expect_identical(samples$included, c(rep(TRUE, 5), FALSE))

  empty <- add_recovery(recovery_parent(reference = character()), "antibiotic", observed_rule())
  outcome <- results_preserving_input(empty)
  expect_identical(outcome$result_state, "available")
  expect_identical(outcome$status, "not_evaluable")
  expect_identical(outcome$reason, "missing_baseline")
  expect_identical(outcome$n_baseline_samples, 0L)
})

test_that("the view preserves complete context without inventing upstream fingerprints", {
  tse <- add_recovery(recovery_parent(), "antibiotic", observed_rule())
  view <- results_preserving_input(tse[, colnames(tse) != "s3"])
  metadata <- S4Vectors::metadata(view)$recoverome_view
  record <- registration_record(tse)
  expect_identical(metadata$schema_version, 1L)
  expect_identical(metadata$selection,
                   list(analysis_id = "antibiotic", level = "episode", scope = "current"))
  expect_identical(metadata$registration$events, record$events)
  expect_identical(metadata$registration$episodes, record$episodes)
  expect_identical(metadata$registration$time_unit, "days")
  expect_identical(metadata$scopes$registration$sample_ids, c("b1", paste0("s", 1:6)))
  expect_identical(metadata$scopes$reference$sample_ids, "b1")
  expect_identical(metadata$scopes$recovery$sample_ids, c("b1", paste0("s", 1:6)))
  expect_identical(metadata$definitions$reference, record$reference$definition)
  expect_identical(metadata$definitions$recovery$threshold, 0.25)
  expect_identical(metadata$provenance$reference$fingerprint, record$reference$fingerprint)
  expect_null(metadata$provenance$registration$fingerprint)
  expect_null(metadata$provenance$deviation$fingerprint)
  expect_identical(metadata$provenance$deviation$results, record$deviation$results)
  expect_identical(metadata$evidence$episode_1$confirmation_run, c("s2", "s3", "s4"))
  expect_identical(metadata$uninterpreted_stages, character())
  expect_false(metadata$validation$summary$validation_complete)
  expect_identical(metadata$validation$summary$dependencies, "not_checked")
  view$confirmation_time <- 99
  expect_identical(registration_record(tse)$recovery$episodes$confirmation_time, 6)
})
